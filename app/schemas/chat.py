"""
Pydantic schemas for Google Gemini AI chat request and response payloads.
"""

from datetime import datetime, timezone
from pydantic import BaseModel, Field, field_validator, AliasChoices


class ChatMessageRequest(BaseModel):
    """
    Request schema for sending a chat message to Gemini AI.
    Rejects empty, whitespace-only, or excessively long messages.
    Accepts either 'message' or 'prompt' key for maximum client compatibility.
    """
    message: str = Field(
        ...,
        validation_alias=AliasChoices("message", "prompt"),
        min_length=1,
        max_length=4000,
        description="The message prompt to send to Gemini (1 to 4000 characters).",
        examples=["Explain how quantum computing works in simple words."],
    )

    @field_validator("message")
    @classmethod
    def validate_not_whitespace(cls, value: str) -> str:
        """Ensures the message does not consist purely of whitespace."""
        trimmed = value.strip()
        if not trimmed:
            raise ValueError("Message cannot be empty or contain only whitespace.")
        return trimmed


class ChatMessageResponse(BaseModel):
    """
    Response schema returning the AI-generated answer and metadata.
    """
    response: str = Field(
        ...,
        description="The text content generated by Google Gemini AI.",
    )
    model: str = Field(
        ...,
        description="The Gemini model used for generation.",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of the generated response.",
    )
